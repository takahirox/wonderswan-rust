fn check(model: Model) {
    let mut m = Machine::new(model);
    m.load_rom(ROM).unwrap();
    let mut stale = vec![0x6d; 32768];
    stale[0..4].copy_from_slice(&[0x0d, 0x60, 0, 0]);
    m.load_save(&stale).unwrap();
    for boot in 1..=2 {
        for _ in 0..4 {
            m.run_frame().unwrap();
        }
        eprintln!(
            "{model:?} boot {boot}: status={:04x}, phases={}, first AX/FLAGS/branches={:02x?}",
            u16::from_le_bytes([m.read_memory(0x400), m.read_memory(0x401)]),
            m.read_memory(0x406),
            &m.save_data()[10..16]
        );
        for (i, value) in expected(model, boot).into_iter().enumerate() {
            let address = 0x400 + 2 * i as u32;
            assert_eq!(
                u16::from_le_bytes([m.read_memory(address), m.read_memory(address + 1)]),
                value,
                "{model:?} boot {boot} RAM word {i}"
            );
            assert_eq!(
                u16::from_le_bytes([m.save_data()[2 * i], m.save_data()[2 * i + 1]]),
                value,
                "{model:?} boot {boot} SRAM word {i}"
            );
        }
        assert!(m.cpu().halted);
        assert_eq!(m.cpu().registers[4], 0x3000);
        assert_eq!(
            &m.framebuffer()[..4],
            if model == Model::Mono {
                &[170, 170, 170, 255]
            } else {
                &[0, 255, 0, 255]
            }
        );
        m.restart();
        assert_eq!(m.frame_number(), 0);
    }
}

#[test]
fn conversion_cartridge_mono() {
    check(Model::Mono);
}
#[test]
fn conversion_cartridge_color() {
    check(Model::Color);
}
#[test]
fn conversion_cartridge_crystal() {
    check(Model::Crystal);
}
