def tiles():
    data = bytearray(128 * 16)
    for char, rows in FONT.items():
        for y, row in enumerate(rows):
            # Stretch 3 columns to 6 pixels and center inside the tile.
            bits = int('0' + ''.join(bit * 2 for bit in row) + '0', 2)
            data[ord(char) * 16 + (y + 1) * 2] = bits
    icons = {
        1: [0x00, 0x7e, 0x42, 0x5a, 0x5a, 0x42, 0x7e, 0x00],
        2: [0x18, 0x3c, 0x7e, 0xff, 0xff, 0x7e, 0x3c, 0x18],
        3: [0xff, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xff],
    }
    for tile, rows in icons.items():
        for y, row in enumerate(rows):
            data[tile * 16 + y * 2] = row
    return data
