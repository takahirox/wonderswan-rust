; Capture actual quotient/remainder/FLAGS plus actual subsequent branch decisions.
; None of the MOV/PUSH/POP/Jcc instructions before branch collection change flags.
%macro observe 5
    pushf
    pop si
    mov [di],%1
    mov [di+2],dx
    mov [di+4],si
    mov bp,0
    jnz %%nz
    or bp,1
%%nz:
    ; OR changed flags: restore the actual saved division flags.
    push si
    popf
    jnc %%nc
    or bp,2
%%nc:
    push si
    popf
    jno %%no
    or bp,4
%%no:
    push si
    popf
    jns %%ns
    or bp,8
%%ns:
    push si
    popf
    jnp %%np
    or bp,16
%%np:
    push si
    popf
    jge %%ge
    or bp,32
%%ge:
    mov [di+6],bp
    add di,8
    cmp %1,%2
    jne failed
    cmp dx,%3
    jne failed
    cmp si,%4
    jne failed
    cmp bp,%5
    jne failed
%endmacro

