; AX and PUSHF are captured before changing arithmetic flags. Each Jcc sees
; the saved conversion flags; branch bits are ZF/CF/OF/SF/PF = 1/2/4/8/16.
%macro convert 7
    mov ax,%3
    push word %4
    popf
    db %1
%if %1 != 0x37 && %1 != 0x3f
    db %2
%endif
    pushf
    pop si
    mov [di],ax
    mov [di+2],si
    mov bp,0
    jnz %%nz
    or bp,1
%%nz:
    push si
    popf
    jnc %%nc
    or bp,2
%%nc:
    push si
    popf
    jno %%no
    or bp,4
%%no:
    push si
    popf
    jns %%ns
    or bp,8
%%ns:
    push si
    popf
    jnp %%np
    or bp,16
%%np:
    mov [di+4],bp
    add di,6
    cmp ax,%5
    jne failed
    cmp si,%6
    jne failed
    cmp bp,%7
    jne failed
%endmacro

